'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('app/src/main/assets/web/index.html','utf8');
const preview=fs.readFileSync('web/index.html','utf8');
assert.equal(html,preview,'Browser preview must match Android asset');
const js=html.split('<script>')[1]?.split('</script>')[0];
assert(js);new Function(js);
const start=js.indexOf('const MUD_LEVEL_PRESETS='),end=js.indexOf('function calculateMud(',start);
assert(start>=0&&end>start);
const {mudTargetChoice,mudTargetChoices,mudLevelGallons,mudLevelInputValues}=new Function('esc',js.slice(start,end)+'return {mudTargetChoice,mudTargetChoices,mudLevelGallons,mudLevelInputValues};')(String);
assert.equal(mudTargetChoice(undefined),'custom','Older saved jobs default to manual target');
assert.equal(mudTargetChoice('empty'),'custom','Zero gallons is not a valid final target');
assert.equal(mudTargetChoice('threequarter'),'threequarter');
assert.equal(mudLevelGallons(1000,'half'),500);
assert.equal(mudLevelGallons(1000,'threequarter'),750);
const ui=mudTargetChoices({targetLevelChoice:'threequarter',targetGallons:'300'},'1000');
assert(ui.includes('name="targetLevelChoice" value="threequarter"'));
assert(ui.includes('name="targetGallons"'));
assert(ui.includes('value="750" readonly'));
assert(ui.includes('data-action="mud-select-target"'));
assert(!ui.includes('data-level="empty"'));
assert(mudTargetChoices({targetGallons:'625'},'1000').includes('value="625"'));
assert.equal(mudLevelInputValues({capacity:'1000',levelChoice:'half',currentGallons:'200'}).currentGallons,'500');
assert(js.includes('targetGallons:target.currentGallons,targetLevelChoice:target.levelChoice'));
assert(js.includes("config.targetLevelChoice='custom'"));
assert(js.includes("case 'mud-select-target':updateMudTargetForm(btn.closest('form'),btn.dataset.level)"));
assert(js.includes('updateMudTargetForm(form);'),'Changing tank capacity must recalculate selected final fraction');
console.log('BoreLab MixLab target fill shortcuts, backward compatibility and UI wiring passed.');
