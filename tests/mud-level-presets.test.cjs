'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('app/src/main/assets/web/index.html','utf8');
const js=html.split('<script>')[1]?.split('</script>')[0];
assert(js);new Function(js);
const start=js.indexOf('const MUD_LEVEL_PRESETS='),end=js.indexOf('function calculateMud(',start);
assert(start>=0&&end>start);
const {mudLevelChoice,mudLevelGallons,mudLevelInputValues}=new Function(js.slice(start,end)+'return {mudLevelChoice,mudLevelGallons,mudLevelInputValues};')();
const known={empty:0,quarter:250,half:500,threequarter:750,full:1000};
for(const [key,gallons] of Object.entries(known))assert.equal(mudLevelGallons('1000',key),gallons);
assert.equal(mudLevelGallons(750,'half'),375);
assert.equal(mudLevelGallons(333,'quarter'),83.25);
assert.equal(mudLevelGallons('','threequarter'),null);
assert.equal(mudLevelGallons(-2,'quarter'),null);
assert.equal(mudLevelGallons(1000,'custom'),null);
assert.equal(mudLevelChoice(undefined),'custom','Old saved data should default to custom gallons');
assert.deepEqual(mudLevelInputValues({capacity:'1000',levelChoice:'threequarter',currentGallons:'90'}),{levelChoice:'threequarter',currentGallons:'750'});
assert.deepEqual(mudLevelInputValues({capacity:'1000',levelChoice:'custom',currentGallons:'625'}),{levelChoice:'custom',currentGallons:'625'});
assert.equal(mudLevelInputValues({capacity:'',levelChoice:'half',currentGallons:'300'}).currentGallons,'','Missing tank capacity cannot use stale gallons');
assert(html.includes('data-action="mud-select-level"'),'Level buttons missing');
assert(js.includes("case 'mud-select-level':updateMudLevelForm(btn.closest('form'),btn.dataset.level)"),'Level button click missing');
assert(js.includes('data-mud-level-code'),'Form must persist level choice');
assert(js.includes("data-form='mud-level'")||js.includes('data-form="mud-level"'),'Set Level dialog missing');
assert(js.includes("updateMudLevelForm(e.target.closest('form'))"),'Tank capacity must recalculate selected fraction');
assert(html.includes('mud-level-choice.active'),'Selected fraction must be visible');
assert(js.includes("config.levelChoice='custom'"),'Actual mix must reset estimate after final volume is logged');
const state={mudTank:{capacity:'1000',currentGallons:'100',targetGallons:'1000',levelChoice:'custom',mode:'topoff'},mudLogs:[]};
const mudConfig=new Function('state',js.slice(js.indexOf('function mudConfig(){'),js.indexOf('const MUD_LEVEL_PRESETS='))+'return mudConfig;')(state);
const saveStart=js.indexOf('function saveMudLevel('),saveEnd=js.indexOf('function archiveMudProduct(',saveStart);
assert(saveStart>=0&&saveEnd>saveStart);
const saves=[];
const saveMudLevel=new Function('state','mudConfig','mudLevelInputValues','save','closeModal','render','notify',
 js.slice(saveStart,saveEnd)+'return saveMudLevel;')
(state,mudConfig,mudLevelInputValues,()=>saves.push('save'),()=>{},()=>{},()=>{});
saveMudLevel({levelChoice:'half',currentGallons:'999'});
assert.equal(state.mudTank.currentGallons,'500','Half-full preset must override the stale submitted number');
assert.equal(state.mudTank.levelChoice,'half');
assert.equal(state.mudLogs.length,0,'Updating an existing premix level must not record any new chemicals');
saveMudLevel({levelChoice:'threequarter',currentGallons:'1'});
assert.equal(state.mudTank.currentGallons,'750');
saveMudLevel({levelChoice:'full',currentGallons:'1'});
assert.equal(state.mudTank.currentGallons,'1000');
assert.equal(state.mudTank.targetGallons,'1000','Target cannot remain below current level');
saveMudLevel({levelChoice:'custom',currentGallons:'620'});
assert.equal(state.mudTank.currentGallons,'620');
assert.equal(state.mudTank.levelChoice,'custom');
assert.equal(saves.length,4);
console.log('BoreLab MixLab fractional tank level calculation, saved modes and premix safety checks passed.');
