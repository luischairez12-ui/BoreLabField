const utilStart=products.indexOf('function sizeKey(');
const utilEnd=products.indexOf('function renderLine(',utilStart);
assert(utilStart>=0&&utilEnd>utilStart);
const math=new Function('sane',products.slice(utilStart,utilEnd)+'return {sizeKey,normalized,plan,summary};')(x=>Number.isFinite(Number(x))?Number(x):0);
assert.equal(math.sizeKey('4"'),math.sizeKey('4 inch'));
assert.notEqual(math.sizeKey('4"'),math.sizeKey('2 inch'));
const shot={feet:175,conduits:[{size:'4 inch',quantity:2,perRunFeet:''},{size:'1.25 inch',quantity:1,perRunFeet:''}]};
const lines=math.plan(shot,10);
assert.deepEqual(lines.map(x=>x.total),[370,185]);
assert.equal(lines.reduce((n,x)=>n+x.total,0),555,'175ft +10 allowance pulled three times totals 555ft');
assert.equal(math.normalized({pipeDiameter:'2 inch'}).length,1,'Legacy single-size shots remain editable');
assert.deepEqual(math.plan({feet:175,conduits:[{size:'4 inch',quantity:2,perRunFeet:180}]},10).map(x=>x.total),[360],'Custom line footage overrides default');
const invStart=products.indexOf('function inventory(');
const invEnd=products.indexOf('function renderPlannerSummary(',invStart);
assert(invStart>=0&&invEnd>invStart);
const data={jobs:[{id:'j',archived:false,allowance:10,shots:[shot]}],reels:[
 {id:'r4',size:'4"',remaining:360,location:'truck',archived:false},
 {id:'r125',size:'1.25 inch',remaining:200,location:'truck',archived:false},
 {id:'r2',size:'2 inch',remaining:999,location:'truck',archived:false}
]};
const inventory=new Function('api','plan','sizeKey','sane',products.slice(invStart,invEnd)+'return inventory;')(
 ()=>({state:()=>data}),math.plan,math.sizeKey,x=>Number.isFinite(Number(x))?Number(x):0);
const counts=inventory().lines;
const four=counts.find(x=>x.key==='4 in'),one=counts.find(x=>x.key==='1.25 in');
assert(four&&one,'Both conduit sizes must be present');
assert.equal(four.required,370);assert.equal(four.available,360,'4-inch pipe can only use its own reels');
assert.equal(one.required,185);assert.equal(one.available,200);
assert.equal(inventory().missing,0);
const editorStart=products.indexOf('function parseEditor('),editorEnd=products.indexOf('function updateFormSummary(',editorStart);
const parseEditor=new Function(products.slice(editorStart,editorEnd)+'return parseEditor;')();
const makeRow=(size,quantity,perRunFeet)=>({querySelector:sel=>{
 const map={'[data-bl-size]':{value:size},'[data-bl-qty]':{value:quantity},'[data-bl-feet]':{value:perRunFeet}};
 return map[sel]||null;
}});
const formFor=rows=>({querySelector:q=>q==='.bl-conduits'?{querySelectorAll:q=>q==='[data-bl-conduit-row]'?rows:[]}:null});
assert.deepEqual(parseEditor(formFor([makeRow('4 inch','2',''),makeRow('1.25 inch','1','')])),shot.conduits);
assert.throws(()=>parseEditor(formFor([makeRow('4 inch','0','')])),/quantity/i);
assert.throws(()=>parseEditor(formFor([makeRow('','2','')])),/size/i);
const parseStart=scanner.indexOf('function parseConduitSpec(');
const parseEnd=scanner.indexOf('function editorRow(',parseStart);
assert(parseStart>=0&&parseEnd>parseStart);
const parser=new Function(scanner.slice(parseStart,parseEnd)+'return {parseSheet,parseConduitSpec,lengthOnLine,lineAddress};')();
