'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const android=fs.readFileSync('app/src/main/assets/web/index.html','utf8');
const preview=fs.readFileSync('web/index.html','utf8');
assert.equal(android,preview,'Android and preview must be identical');
const a=fs.readFileSync('app/src/main/assets/web/assets/crew-hero.png');
const b=fs.readFileSync('web/assets/crew-hero.png');
assert(a.equals(b),'Bundled art should be identical in Android and web preview');
assert(a.subarray(0,8).equals(Buffer.from('89504e470d0a1a0a','hex')),'Image must be valid PNG');
assert.equal(a.readUInt32BE(16),320);
assert.equal(a.readUInt32BE(20),140);
const js=android.split('<script>')[1]?.split('</script>')[0];
assert(js);new Function(js);
const start=js.indexOf('function uxRigArt(){'),end=js.indexOf('function actionTile(tool){',start);
assert(start>=0&&end>start,'Artwork component must be present');
const illustration=new Function(js.slice(start,end)+'return uxRigArt();')();
assert(illustration.startsWith('<img class="ux-rig-art"'));
assert(illustration.includes('src="assets/crew-hero.png"'));
assert(illustration.includes('aria-hidden="true"'));
assert(!illustration.includes('<svg'), 'Old blocky stick-figure SVG must be removed');
assert(android.includes('.ux-rig-art{')&&android.includes('object-fit:contain'),'Hero positioning unchanged');
assert(android.includes('data-action="open-job"'),'Active job remains clickable');
assert(android.includes('data-page="jobs"'),'Multiple-job navigation preserved');
assert(android.includes('data-page="dayassist"'),'End-of-Day Assistant preserved');
assert(js.includes("const KEY='borelab-field-v0.1'"),'Do not change saved records key');
console.log('BoreLab crew art: local PNG bundled in both builds; generated illustration replaces geometric SVG and job data survives.');
