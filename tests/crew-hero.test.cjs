'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync('app/src/main/assets/web/index.html','utf8');
const preview=fs.readFileSync('web/index.html','utf8');
assert.equal(html,preview,'Android and preview HTML must match exactly');
const script=html.split('<script>')[1]?.split('</script>')[0];
assert(script);
new Function(script);
const begin=script.indexOf('function uxRigArt(){');
const end=script.indexOf('function actionTile(tool){',begin);
assert(begin>=0&&end>begin,'Hero illustration function missing');
const art=new Function(script.slice(begin,end)+'return uxRigArt();')();
assert(art.startsWith('<svg class="ux-rig-art" viewBox="0 0 320 140"'));
assert(art.endsWith('</svg>'));
assert(art.includes('id="boreCrewLand"'),'Soft BoreLab landscape gradient missing');
assert(art.includes('fill="#617f90"'),'Standing locator silhouette missing');
assert(art.includes('fill="#627f8e"'),'Crouched crew silhouette missing');
assert(art.includes('fill="#5c7888"'),'Crew supervisor silhouette missing');
assert(art.includes('stroke="#d7e6eb"'),'High-visibility vest accents missing');
assert(!art.includes('width="110" height="18"'),'Old machine track shape must be removed');
assert(html.includes('.ux-rig-art{'),'Existing illustration placement must not change');
assert(html.includes('function renderHome()'),'Home dashboard must be preserved');
assert(html.includes('data-action="open-job"'),'Active Job card must remain functional');
assert(html.includes('data-page="jobs"'),'Multi-job navigation must be preserved');
assert(html.includes('data-page="dayassist"'),'End-of-day navigation must be preserved');
assert(script.includes("const KEY='borelab-field-v0.1'"),'Offline data storage key must stay unchanged');
console.log('BoreLab 0.12.1 crew silhouette: SVG, visual layout hooks and saved-data compatibility passed.');
