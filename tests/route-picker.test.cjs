'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('app/src/main/assets/web/index.html','utf8');
const js=html.split('<script>')[1]?.split('</script>')[0];
assert(js,'Missing embedded script');
new Function(js);
assert(js.includes('let routeMenuOpen=false;'),'Route options must be collapsed by default');
const i=js.indexOf("function renderPlanner(){"),j=js.indexOf("function renderPhotos(){",i);
assert(i>=0&&j>i);
const planner=js.slice(i,j);
assert(planner.includes('data-action="toggle-route-menu"'),'Route menu header must be tappable');
assert(planner.includes('aria-expanded=')&&planner.includes("routeMenuOpen?'true':'false'"),'Accessible expanded state missing');
assert(planner.includes('aria-controls="route-mode-choices"'),'Menu control target missing');
assert(planner.includes("routeMenuOpen?'':'hidden'"),'Choices must be hidden when collapsed');
assert(planner.includes('<small>')&&planner.includes('esc(modeName)'),'Selected route must remain visible');
assert(!planner.includes('Active plan:'),'Remove duplicate route header');
assert(js.includes("case 'toggle-route-menu':routeMenuOpen=!routeMenuOpen;render();break;"),'Tap must toggle the menu');
assert(js.includes("state.routeMode=btn.dataset.mode;routeMenuOpen=false;save();render();"),'Selecting a route must save and collapse');
assert(html.includes('.route-picker-toggle:focus-visible'),'Keyboard focus style missing');
assert(html.includes('.route-mode-choices[hidden]{display:none!important}'),'Collapsed options must not display');
console.log('Compact route-picker behavior checks passed.');
